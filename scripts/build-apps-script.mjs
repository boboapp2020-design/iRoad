// Builds apps-script/dist/Code.gs: the shared verification module (TypeScript)
// bundled as the global `RRVerify`, followed by the backend source files.
// Paste dist/Code.gs + dist/appsscript.json into the Apps Script editor, or push with clasp.
import { build } from 'esbuild';
import { mkdirSync, readdirSync, readFileSync, writeFileSync, copyFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = join(root, 'apps-script', 'src');
const distDir = join(root, 'apps-script', 'dist');
mkdirSync(distDir, { recursive: true });

const result = await build({
  entryPoints: [join(root, 'shared', 'verification', 'index.ts')],
  bundle: true,
  format: 'iife',
  globalName: 'RRVerify',
  target: 'es2019',
  write: false,
  legalComments: 'none',
  charset: 'utf8',
});
// Drop the bundle's top-level "use strict" so it does not apply to the whole concatenated file.
const verification = result.outputFiles[0].text.replace(/^\s*"use strict";\s*/, '');

const files = readdirSync(srcDir).filter((f) => f.endsWith('.js')).sort();
const parts = [
  '/* Road Repair Tracker — Apps Script backend. GENERATED by scripts/build-apps-script.mjs; do not edit. */',
  '/* ===== shared/verification (bundled) ===== */',
  verification.trim(),
  ...files.map((f) => `/* ===== ${f} ===== */\n${readFileSync(join(srcDir, f), 'utf8').trim()}`),
  '',
];
writeFileSync(join(distDir, 'Code.gs'), parts.join('\n\n'));
copyFileSync(join(root, 'apps-script', 'appsscript.json'), join(distDir, 'appsscript.json'));
console.log(`Wrote apps-script/dist/Code.gs (${files.length} source files + verification bundle)`);
